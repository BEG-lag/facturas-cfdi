const DICTS: Record<Lang, Dict> = { es, en };

let current: Lang = 'es';

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: string, params?: Record<string, string | number>, lang: Lang = current): string {
  const template = DICTS[lang][key] ?? DICTS.es[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function hasKey(key: string, lang: Lang = 'es'): boolean {
  return key in DICTS[lang];
}

export function allKeys(lang: Lang): string[] {
  return Object.keys(DICTS[lang]);
}
